/*
 * Converts the dashboards.business wordmark text into vector outlines so the
 * SVGs render identically everywhere (print, app stores, email) with no font
 * dependency. Font: Outfit ExtraBold (SIL Open Font License 1.1).
 *
 *   cd brand/tools && npm install && npm run outline
 */
const fs = require('fs');
const path = require('path');
const opentype = require('opentype.js');

const fontFile = require.resolve('@fontsource/outfit/files/outfit-latin-800-normal.woff');
const font = opentype.parse(new Uint8Array(fs.readFileSync(fontFile)).buffer);
const TRACKING = -0.04; // em, matches the CSS letter-spacing

const VIOLET = '#6B4EFF', CORAL = '#FF5C7A';
const out = path.join(__dirname, '..', 'logo');

function textPath(text, x, y, size) {
  const p = font.getPath(text, x, y, size, { kerning: true, letterSpacing: TRACKING });
  return { d: p.toPathData(2), box: p.getBoundingBox() };
}
const r = (n) => Math.round(n * 100) / 100;

/* ---------- stacked wordmark ---------- */
function stacked(ink, label) {
  const top = textPath('dash', 4, 34, 30);
  const dotX = top.box.x2 + 1;
  const dot = textPath('.', dotX, 34, 30);
  const bottom = textPath('boards', 2, 88, 64);
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 280 96" width="280" height="96" role="img" aria-label="${label}">
  <!-- Outlined paths: Outfit ExtraBold (OFL-1.1). Generated by brand/tools/outline-wordmark.cjs -->
  <path fill="${VIOLET}" d="${top.d}"/>
  <path fill="${CORAL}" d="${dot.d}"/>
  <path fill="${ink}" d="${bottom.d}"/>
</svg>
`;
}
fs.writeFileSync(path.join(out, 'wordmark-light.svg'), stacked('#12152A', 'dashboards.business wordmark'));
fs.writeFileSync(path.join(out, 'wordmark-dark.svg'), stacked('#FFFFFF', 'dashboards.business wordmark'));

/* ---------- horizontal lockup ---------- */
(function lockup() {
  const size = 40, x0 = 82, y0 = 47;
  const a = textPath('dashboards', x0, y0, size);
  const b = textPath('.business', a.box.x2 + 0.5, y0, size);
  const w = Math.ceil(b.box.x2 + 6);
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${w} 64" width="${w}" height="64" role="img" aria-label="dashboards.business">
  <!-- Outlined paths: Outfit ExtraBold (OFL-1.1). Generated by brand/tools/outline-wordmark.cjs -->
  <rect width="64" height="64" rx="16" fill="${VIOLET}"/>
  <rect x="14" y="36" width="8" height="14" rx="4" fill="#FFFFFF"/>
  <rect x="28" y="26" width="8" height="24" rx="4" fill="#FFFFFF"/>
  <rect x="42" y="14" width="8" height="36" rx="4" fill="#FFFFFF"/>
  <circle cx="18" cy="20" r="5" fill="${CORAL}"/>
  <path fill="#12152A" d="${a.d}"/>
  <path fill="${VIOLET}" d="${b.d}"/>
</svg>
`;
  fs.writeFileSync(path.join(out, 'lockup-horizontal.svg'), svg);
  const dark = svg.replace('fill="#12152A"', 'fill="#FFFFFF"').replace(`fill="${VIOLET}" d="${b.d}"`, `fill="#A594FF" d="${b.d}"`);
  fs.writeFileSync(path.join(out, 'lockup-horizontal-dark.svg'), dark);
})();

console.log('Wrote outlined wordmark + lockup SVGs to', path.relative(process.cwd(), out));
